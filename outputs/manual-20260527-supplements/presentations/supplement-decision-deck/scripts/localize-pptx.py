def has_cjk(text: str) -> bool:
    return bool(re.search(r"[\u4e00-\u9fff]", text))

def transform_pptx(src: Path, dst: Path, mode: str) -> list[str]:
    leftovers: list[str] = []
    with zipfile.ZipFile(src, "r") as zin, zipfile.ZipFile(dst, "w", zipfile.ZIP_DEFLATED) as zout:
        for item in zin.infolist():
            data = zin.read(item.filename)
            if item.filename.endswith(".xml") and item.filename.startswith("ppt/"):
                try:
                    root = ET.fromstring(data)
                    changed = False
                    for node in root.findall(".//a:t", NS):
                        if node.text:
                            old = node.text
                            if mode == "hans":
                                node.text = cc.convert(old)
                            elif mode == "en":
                                node.text = EN_MAP.get(old, old)
                                if has_cjk(node.text):
                                    leftovers.append(node.text)
                            changed = changed or (node.text != old)
                    if changed:
                        data = ET.tostring(root, encoding="utf-8", xml_declaration=True)
                except ET.ParseError:
                    pass
            zout.writestr(item, data)
    return sorted(set(leftovers))

